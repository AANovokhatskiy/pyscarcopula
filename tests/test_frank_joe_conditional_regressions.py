def test_joe_root_resolution_when_log_coordinate_is_near_zero():
    # Adjacent z=log(-log(1-u)) doubles can exponentiate to the same x.
    # The solver must recognize a root bracket in x rather than exhaust its
    # budget while seeking an unrepresentable probability residual.
    given, q, theta = .6311327929962085, .20674914821484136, 1e10
    actual = pair.h_inverse(JoeCopula(), q, given, theta)[0]
    # At this theta the two omitted exp(-theta*x) terms are smaller than exp(-1e9).
    # Consequently the conditional reduces to an independent analytic logistic
    # root, evaluated directly in x to avoid the solver's logarithmic coordinate.
    beta = (theta-1)/theta
    x = -np.log1p(-given) - np.log(np.expm1(-np.log(q)/beta))/theta
    expected = -np.expm1(-x)
    assert abs(actual-expected) <= 2*np.spacing(expected)
